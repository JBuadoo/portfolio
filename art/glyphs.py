"""JB Pixel - a hand-authored bitmap font used for display type and in-art text.

Each glyph is a list of up to 9 rows (rows 0-6 = cap height, 7-8 = descender).
'#' = ink. Width = length of row. Advance = width + 1.
"""

G = {}


def g(ch, rows):
    rows = rows.split("|") if isinstance(rows, str) else rows
    w = max(len(r) for r in rows)
    rows = [r.ljust(w, ".") for r in rows]
    while len(rows) < 9:
        rows.append("." * w)
    G[ch] = rows


